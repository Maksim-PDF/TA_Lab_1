#!/usr/bin/env python3
# -*- coding: utf-8 -*-

# Есть зашифрованное сообщение

secret_message = [
    'квевтфпп6щ3стмзалтнмаршгб5длгуча',
    'дьсеы6лц2бане4т64ь4б3ущея6втщл6б',
    'т3пплвце1н3и2кд4лы12чф1ап3бкычаь',
    'ьд5фму3ежородт9г686буиимыкучшсал',
    'бсц59мегщ2лятьаьгенедыв9фк9ехб1а',
]

# Нужно расшифровать сообщение и вывести на консоль в удобочитаемом виде.
# Должна получиться фраза на русском языке.
#
# Ключ к расшифровке:
#   первое слово - 4-я буква
#   второе слово - буквы с 10 по 13, включительно
#   третье слово - буквы с 6 по 15, включительно, через одну
#   четвертое слово - буквы с 8 по 13, включительно, в обратном порядке
#   пятое слово - буквы с 17 по 21, включительно, в обратном порядке
#
# Обратите внимание:
#   даны номера букв, а не индексы
#   срез не включает последний индекс
#   4-е и 5-е слова нужно получить за 1 срез


def decrypt_message(messages):
    """Расшифровывает сообщение по ключу и возвращает фразу.

    Каждая строка списка содержит одно зашифрованное слово.
    Номера букв в ключе соответствуют индекс + 1.
    """
    decrypted_words = (
        messages[0][3],           # 4-я буква
        messages[1][9:13],        # буквы с 10 по 13
        messages[2][5:15:2],      # буквы с 6 по 15 через одну
        messages[3][7:13][::-1],  # с 8 по 13 в обратном порядке
        messages[4][16:21][::-1], # с 17 по 21 в обратном порядке
    )
    return ' '.join(decrypted_words)


def main():
    print(decrypt_message(secret_message))


# Защита от автоматического выполнения при импорте модуля
if __name__ == "__main__":
    main()
