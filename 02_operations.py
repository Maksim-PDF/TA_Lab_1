# Расставьте знаки операций "плюс", "минус", "умножение" и скобки
# между числами "1 2 3 4 5" так, чтобы получилось число "25".
#
# Использовать нужно только указанные знаки операций, но не обязательно все перечисленные.
# Порядок чисел нужно сохранить.

# Пример для чисел "1 2 3" и "9"
# (1 + 2) * 3


def compute_result():
    """Возвращает значение выражения из чисел 1 2 3 4 5, равного 25."""
    result = 1 * 2 + 3 + 4 * 5
    return result


def main():
    print(compute_result())


# Защита от автоматического выполнения при импорте модуля
if __name__ == "__main__":
    main()
